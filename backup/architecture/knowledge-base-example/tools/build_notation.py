def likec4_spec(icon_dir: str) -> str:
    """LikeC4 specification. icon_dir is relative to the file the spec is written to."""
    out = ["// Generated by tools/build_notation.py from tools/notation_data.py — do not edit.",
           "// ArchiMate 3.2 notation of the AIToolbox design system: one element kind per type.", "",
           "specification {"]
    for lid, (label, lf, li, df, di) in LAYERS.items():
        out.append(f"  color ax-{lid} {lf}   // {label} (light fill; exact light/dark tokens in archimate-likec4.css)")
    out.append("")
    for (eid, name, layer, aspect, shape, glyph, _d) in ELEMENTS:
        out.append(f"  element {eid} {{")
        out.append(f"    notation '{name}'")
        out.append("    style {")
        out.append(f"      color ax-{layer}")
        if shape == "group":
            out += ["      border dashed", "      opacity 0%"]
        else:
            out += ["      border solid", "      opacity 100%"]
            out.append(f"      icon {icon_dir}/{eid}.svg")
        out += ["      shape rectangle", "      size sm", "      textSize sm", "      padding sm", "    }", "  }"]
    out.append("")
    for (rid, name, line, _s, _t, l_line, l_tail, l_head, _d) in RELATIONSHIPS:
        out += [f"  relationship {rid} {{", f"    notation '{name}'", f"    line {l_line}", f"    tail {l_tail}", f"    head {l_head}", "  }"]
    out.append("")
    # Plateau membership and change are relationships, not tags (see tools/ea_model.py): no plateau or change tags.
    out.append("  // Status (changed only by a Checkpoint decision, INV-12)")
    for t, c in STATUS_TAGS.items():
        out += [f"  tag {t} {{", f"    color {c}", "  }"]
    out.append("}")
    return "\n".join(out) + "\n"


