#!/usr/bin/env python3
"""Project the knowledge base into dist/ (run tools/validate.py first: it writes dist/bb.json and dist/validation.json).

  dist/likec4/      LikeC4 project: model/bb/*.c4 + ArchiMate notation spec + icons + views.generated.c4
                    (landscape per plateau, gap per pair of plateaus, roadmap, chain, motivation, one view per element)
  dist/model.json   building blocks + Markdown + gaps + validation, for agents and the Context pack
  dist/index.html   Architecture feature page (tools/site.template.html); tools/build_likec4.py then embeds LikeC4

Usage: python3 tools/generate.py [root]
Env:   MMDC / MMDC_PUPPETEER for Mermaid → SVG (otherwise diagrams stay as source)
"""
from __future__ import annotations
import hashlib, html, json, os, re, shutil, subprocess, sys, tempfile
from pathlib import Path
import markdown
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ea_model import load_model, gap, addressed_by, PLATEAUS  # noqa: E402
from build_notation import likec4_spec  # noqa: E402

ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"
MERMAID_RE = re.compile(r"```mermaid\n(.*?)```", re.S)
MMDC = os.environ.get("MMDC") or shutil.which("mmdc")
MMDC_PP = os.environ.get("MMDC_PUPPETEER")
PLATEAU_LABEL = {"baseline": "Baseline", "transition-1": "Transition 1", "transition-2": "Transition 2", "target": "Target"}
CORE_RELATIONS = ["composition", "aggregation", "assignment", "serving", "access", "triggering", "flow", "influence", "association", "specialization"]


# ---------- Markdown + Mermaid ----------
def render_mermaid(src: str, theme: str, cache: Path) -> str | None:
    if not MMDC:
        return None
    key = hashlib.sha1((theme + src).encode()).hexdigest()[:12]
    out = cache / f"{key}.svg"
    if not out.exists():
        with tempfile.TemporaryDirectory() as td:
            inp = Path(td) / "d.mmd"; inp.write_text(src, encoding="utf-8")
            cmd = [MMDC, "-i", str(inp), "-o", str(out), "-t", theme, "-b", "transparent", "-I", f"m{key}", "-q"]
            if MMDC_PP:
                cmd += ["-p", MMDC_PP]
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
            if r.returncode != 0 or not out.exists():
                print(f"  mermaid render failed ({theme}): {r.stderr.strip()[:200]}")
                return None
    return re.sub(r"^<\?xml[^>]*>\s*", "", out.read_text(encoding="utf-8"))


def body_to_html(body: str, cache: Path) -> str:
    blocks: list[str] = []

    def repl(m):
        src = m.group(1).strip()
        light, dark = render_mermaid(src, "neutral", cache), render_mermaid(src, "dark", cache)
        blocks.append(f'<div class="diagram"><div class="dg-light">{light}</div><div class="dg-dark">{dark}</div></div>'
                      if light and dark else f'<pre class="mermaid">{html.escape(src)}</pre>')
        return f"\n\nMERMAIDBLOCK{len(blocks) - 1}END\n\n"

    body = re.sub(r"^\s*# [^\n]*\n", "", body, count=1)
    out = markdown.markdown(MERMAID_RE.sub(repl, body), extensions=["tables", "fenced_code", "sane_lists"])
    for i, b in enumerate(blocks):
        out = out.replace(f"<p>MERMAIDBLOCK{i}END</p>", b)
    return out


# ---------- LikeC4 ----------
def vid(fqn: str) -> str:
    return "v_" + re.sub(r"[^A-Za-z0-9_]", "_", fqn)


def q(s: str) -> str:
    s = str(s).replace("\n", " ")
    return '"' + s.replace('"', "'") + '"' if "'" in s else "'" + s + "'"


def plateaus_of(bb: dict, app: str) -> list[dict]:
    order = bb.get("plateauOrder", {}).get(app) or PLATEAUS
    ps = [e for e in bb["elements"].values() if e["kind"] == "plateau" and e["application"] == app]
    return sorted(ps, key=lambda e: order.index(e["id"].split(".")[-1]) if e["id"].split(".")[-1] in order else 99)


def members(bb: dict, app: str, plateau: str, level: str) -> list[str]:
    """Building blocks of one level in one plateau (membership comes from relationships, see ea_model)."""
    return sorted(i for i, e in bb["elements"].items() if e["application"] == app and e["level"] == level and plateau in e["plateaus"])


def include(ids: list[str]) -> list[str]:
    return [f"    include {', '.join(ids)}"] if ids else []


def gen_views(bb: dict) -> str:
    E = bb["elements"]
    apps = sorted({e["application"] for e in E.values() if e["application"]})
    out = ["// Generated by tools/generate.py — do not edit. Hand-written views live in model/bb/views.c4.", "views {"]
    for app in apps:
        ps = plateaus_of(bb, app)
        names = [p["id"].split(".")[-1] for p in ps]
        for p in ps:
            t = p["id"].split(".")[-1]
            out += [f"  view landscape_{t.replace('-', '_')} {{", f"    title {q(p['title'] + ' · ' + app)}",
                    f"    description {q('Building blocks in the ' + PLATEAU_LABEL.get(t, t) + ' plateau. ' + (p['description'] or ''))}",
                    "    include abb, sbb",
                    *include(members(bb, app, t, "abb")),
                    *include(members(bb, app, t, "sbb")),
                    "    exclude * -> * where kind is association",
                    "    autoLayout TopBottom 40 70", "  }"]
        pairs = list(zip(names, names[1:]))
        if len(names) > 2:
            pairs.append((names[0], names[-1]))
        for a, b in pairs:
            g = {x["id"]: x["change"] for x in gap(bb, a, b)}
            by = {c: [i for i, ch in g.items() if ch == c] for c in ("new", "changed", "retired", "unchanged")}
            out += [f"  view gap_{a.replace('-', '_')}_{b.replace('-', '_')} {{",
                    f"    title {q('Gap · ' + PLATEAU_LABEL.get(a, a) + ' → ' + PLATEAU_LABEL.get(b, b) + ' · ' + app)}",
                    "    description 'New: solid, full colour · Changed: dotted border · Retired: dashed and faded · Unchanged: faded.'",
                    "    include abb, sbb", f"    include {', '.join(sorted(g))}",
                    "    exclude * -> * where kind is association", "    autoLayout TopBottom 40 70"]
            if by["unchanged"]:
                out += [f"    style {', '.join(sorted(by['unchanged']))} {{", "      opacity 45%", "    }"]
            if by["changed"]:
                out += [f"    style {', '.join(sorted(by['changed']))} {{", "      border dotted", "    }"]
            if by["retired"]:
                out += [f"    style {', '.join(sorted(by['retired']))} {{", "      border dashed", "      opacity 30%", "    }"]
            out.append("  }")
        out += ["  view roadmap {", f"    title {q('Roadmap · ' + app)}",
                "    description 'Plateaus, the work packages that realise them, and the gaps between them.'",
                f"    include imp.{app}.*", "    autoLayout LeftRight 40 80", "  }"]
        out += ["  view index {", f"    title {q('Chain · ' + app + ' · Requirement → ABB → SBB (target)')}",
                "    description 'Realization chain of the target plateau. Detailed design (DD) is text: model/dd/*.md.'",
                f"    include req.{app}.*", *include(members(bb, app, names[-1], "abb")), *include(members(bb, app, names[-1], "sbb")),
                *[f"    exclude * -> * where kind is {k}" for k in CORE_RELATIONS], "    autoLayout RightLeft 40 70", "  }"]
    # one view per element: chain up through realization + direct neighbours
    for eid, e in E.items():
        if e["level"] not in ("requirement", "abb", "sbb", "migration", "motivation"):
            continue
        near = {eid}
        for r in e["in"] + e["out"]:
            near.add(r["source"]); near.add(r["target"])
        cur, seen = eid, set()
        while cur not in seen:
            seen.add(cur)
            ups = [r["target"] for r in E[cur]["out"] if r["kind"] == "realization" and r["target"] in E
                   and E[r["target"]]["level"] in ("abb", "requirement", "motivation")]
            if not ups:
                break
            near.update(ups); cur = ups[0]
        near = sorted(n for n in near if n in E)
        out += [f"  view {vid(eid)} of {eid} {{", f"    title {q(e['title'])}",
                f"    include {', '.join(near)}", "    autoLayout RightLeft 40 60", "  }"]
    out.append("}")
    return "\n".join(out) + "\n"


def write_likec4_project(bb: dict) -> None:
    proj = DIST / "likec4"
    if proj.exists():
        shutil.rmtree(proj)
    (proj / "icons").mkdir(parents=True)
    for f in (ROOT / "model" / "bb").rglob("*.c4"):          # includes changes/<work package>.c4
        if f.name != "_archimate.spec.c4":
            dest = proj / f.relative_to(ROOT / "model" / "bb")
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(f, dest)
    shutil.copy(ROOT / "model" / "bb" / "likec4.config.json", proj / "likec4.config.json")
    for f in (ROOT / "design-system" / "archimate" / "icons" / "likec4").glob("*.svg"):
        shutil.copy(f, proj / "icons" / f.name)
    (proj / "archimate.spec.c4").write_text(likec4_spec("./icons"), encoding="utf-8")
    (proj / "views.generated.c4").write_text(gen_views(bb), encoding="utf-8")


def c4_source(fqn: str) -> tuple[str, str]:
    """The block that declares an element in model/bb/*.c4 (for the Source tab)."""
    name = fqn.split(".")[-1]
    for f in sorted((ROOT / "model" / "bb").rglob("*.c4")):
        lines = f.read_text(encoding="utf-8").splitlines()
        for i, line in enumerate(lines):
            if re.match(rf"^\s*{re.escape(name)} = [a-z-]+ ", line):
                depth, block = 0, []
                for l2 in lines[i:]:
                    block.append(l2)
                    depth += l2.count("{") - l2.count("}")
                    if depth <= 0 and ("{" in "".join(block) or not l2.rstrip().endswith("{")):
                        break
                ind = len(block[0]) - len(block[0].lstrip())
                return f.relative_to(ROOT).as_posix(), "\n".join(b[ind:] for b in block)
    return "model/bb", ""


# ---------- page data ----------
def page_data(bb: dict, md: dict, report: dict, schema: dict, notation: dict, cache: Path) -> dict:
    E = bb["elements"]
    elements = []
    for eid, e in E.items():
        path, src = c4_source(eid)
        d = {k: e[k] for k in ("id", "level", "kind", "title", "application", "description", "tags", "plateaus", "change", "status",
                               "metadata", "owner", "module", "workItemId", "contract", "adr", "domainRef")}
        d["_path"], d["_source"], d["_lang"] = path, src, "likec4"
        d["addressedBy"] = addressed_by(bb, eid) if e["level"] in ("abb", "sbb") else []
        d["dd"] = sorted(mid for mid, m in md.items() if m["fm"].get("level") == "dd" and eid in (m["fm"].get("realizes") or []))
        d["view"] = vid(eid)
        if eid in md:                                     # requirement details or a note
            fm = md[eid]["fm"]
            for k in ("acceptance", "decisionTable", "operational", "updatedAt"):
                if k in fm:
                    d[k] = fm[k]
            d["_html"] = body_to_html(md[eid]["body"], cache)
            d["_detailPath"] = md[eid]["path"].relative_to(ROOT).as_posix()
        elements.append(d)
    arbs = []
    for mid, m in md.items():
        fm = m["fm"]
        lvl = fm.get("level")
        if lvl in ("dd", "adr"):
            d = dict(fm)
            d["_html"] = body_to_html(m["body"], cache)
            d["_path"], d["_lang"] = m["path"].relative_to(ROOT).as_posix(), "yaml"
            d["_source"] = yaml.safe_dump(fm, sort_keys=False, allow_unicode=True, width=100)
            elements.append(d)
        elif lvl == "arb":
            sections = re.findall(r"^## (.+?)\n(.*?)(?=^## |\Z)", m["body"], flags=re.S | re.M)
            a = dict(fm)
            a["sections"] = [{"title": t.strip(), "html": body_to_html(b, cache)} for t, b in sections]
            a["readiness"] = report["arbs"][mid]
            a["_path"] = m["path"].relative_to(ROOT).as_posix()
            arbs.append(a)
    apps = sorted({e["application"] for e in E.values() if e["application"]})
    landscapes = []
    for app in apps:
        ps = plateaus_of(bb, app)
        names = [p["id"].split(".")[-1] for p in ps]
        pairs = list(zip(names, names[1:])) + ([(names[0], names[-1])] if len(names) > 2 else [])
        landscapes.append({
            "application": app,
            "plateaus": [{"id": p["id"], "tag": p["id"].split(".")[-1], "title": p["title"], "description": p["description"],
                          "view": "landscape_" + p["id"].split(".")[-1].replace("-", "_")} for p in ps],
            "gaps": [{"from": a, "to": b, "view": f"gap_{a.replace('-', '_')}_{b.replace('-', '_')}",
                      "items": [dict(g, addressedBy=addressed_by(bb, g["id"])) for g in gap(bb, a, b)]} for a, b in pairs],
        })
    used = {e["kind"] for e in E.values()}
    return {
        "elements": elements, "relations": bb["relations"], "arbs": arbs, "landscapes": landscapes,
        "validation": {"summary": report["summary"], "checks": report["checks"]},
        "notation": {x["id"]: {"name": x["name"], "layer": x["layer"], "svg": x["svg"]} for x in notation["elements"] if x["id"] in used},
        "layers": {l["id"]: l["label"] for l in notation["layers"]},
        "relationshipNames": {r["id"]: r["name"] for r in notation["relationships"]},
        "kindMapping": schema["$defs"]["kindMapping"],
        "views": sorted(bb["views"]),
    }


def main() -> int:
    for need in ("bb.json", "validation.json"):
        if not (DIST / need).exists():
            print(f"dist/{need} missing: run tools/validate.py first"); return 1
    bb = json.loads((DIST / "bb.json").read_text(encoding="utf-8"))
    report = json.loads((DIST / "validation.json").read_text(encoding="utf-8"))
    if report["summary"]["errors"]:
        print("refusing to generate: tools/validate.py reports errors"); return 1
    schema = json.loads((ROOT / "ea-schema.json").read_text(encoding="utf-8"))
    notation = json.loads((ROOT / "design-system" / "archimate" / "notation.json").read_text(encoding="utf-8"))
    md, errors = load_model(ROOT)
    write_likec4_project(bb)
    cache = DIST / ".mermaid-cache"; cache.mkdir(exist_ok=True)
    data = page_data(bb, md, report, schema, notation, cache)
    (DIST / "model.json").write_text(json.dumps({k: v for k, v in data.items() if k != "notation"}, indent=1, ensure_ascii=False), encoding="utf-8")
    css = (ROOT / "design-system" / "archimate" / "archimate.css").read_text(encoding="utf-8")
    bridge = (ROOT / "design-system" / "archimate" / "tokens-bridge.css").read_text(encoding="utf-8")
    # the artifact viewer switches themes with data-theme, the app with html.dark: the bridge must answer both
    bridge = bridge.replace(":root, html.light {", ':root, html.light, :root[data-theme="light"] {').replace(":root:not(.light) {", ':root:not(.light):not([data-theme="light"]) {').replace("html.dark {", 'html.dark, :root[data-theme="dark"] {')
    payload = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    tpl = (ROOT / "tools" / "site.template.html").read_text(encoding="utf-8")
    (DIST / "index.html").write_text(tpl.replace("/*__TOKENS_BRIDGE__*/", bridge).replace("/*__ARCHIMATE_CSS__*/", css).replace("__MODEL_JSON__", payload), encoding="utf-8")
    print(f"generated dist/likec4/ ({len(bb['elements'])} building blocks, views.generated.c4), dist/model.json, dist/index.html")
    return 0


if __name__ == "__main__":
    sys.exit(main())
